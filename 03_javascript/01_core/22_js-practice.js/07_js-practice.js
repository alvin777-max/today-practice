/*
======================================================================
문제 5. 반복문 — 조건에 맞는 수의 개수와 합계
======================================================================

1부터 20까지의 정수 중 3의 배수인 수를 찾고 개수와 합계를 구하세요.

조건
- for문으로 1부터 20까지 확인합니다.
- 나머지 연산자(%)와 조건문으로 3의 배수를 판별합니다.
- 해당 숫자를 찾을 때마다 출력합니다.
- 개수와 합계는 변수로 누적합니다.
- 반복문 종료 후 개수와 합계를 출력합니다.
- 배열이나 함수를 사용하지 않습니다.

예상 출력
3
6
9
12
15
18
개수: 6
합계: 63
*/

// 문제 5 풀이

let number = 0;
let total = 0;
for (let i = 1; i <= 20; i++) {
    if (i % 3 === 0) {
        console.log(i)
        number += 1;
        total += i;
    }
}
console.log(`개수: ${number}`);
console.log(`합계: ${total}`);