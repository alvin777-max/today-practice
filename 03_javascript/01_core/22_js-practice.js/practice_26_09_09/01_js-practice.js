/*
======================================================================
문제 1. 회원의 배송지 확인하기
======================================================================

회원 객체에 배송지 정보가 있을 수도 있고 없을 수도 있습니다.
옵셔널 체이닝 연산자를 사용하여 도시를 안전하게 조회하세요.

입력
const user1 = {
    name: '홍길동',
    address: {
        city: '서울'
    }
};

const user2 = {
    name: '유관순'
};

조건
- 입력 객체는 그대로 사용합니다.
- 옵셔널 체이닝 연산자(?.)를 사용합니다.
- if문이나 논리 AND 연산자(&&)를 사용하지 않습니다.
- user1과 user2의 도시를 각각 출력합니다.

예상 출력
서울
undefined
*/

// 문제 1 풀이

const user1 = {
    name: '홍길동',
    address: {
        city: '서울'
    }
};

const user2 = {
    name: '유관순'
};

console.log(user1?.address?.city);
console.log(user2?.address?.city);